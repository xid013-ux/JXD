  s.addText('这一页回答', { x:1.0, y:2.02, w:3.1, h:0.3, fontFace:CN, fontSize:12, bold:true, color:MID, margin:0 });
  s.addText(ask, { x:1.0, y:2.38, w:3.1, h:0.95, fontFace:CN, fontSize:15, bold:true, color:DEEP, margin:0, valign:'top' });

  // 右：必须出现
  s.addText('本页必须出现', { x:4.7, y:1.9, w:7.8, h:0.3, fontFace:CN, fontSize:12, bold:true, color:MID, margin:0 });
  s.addText(items.map((t, k) => ({ text:t, options:{ bullet:true, breakLine: k !== items.length - 1 } })),
    { x:4.7, y:2.25, w:7.8, h:2.35, fontFace:CN, fontSize:11.5, color:'333B44', paraSpaceAfter:4, margin:0, valign:'top' });

  // 填写区
  s.addShape(pres.ShapeType.rect, { x:0.8, y:4.8, w:11.7, h:1.8,
    fill:{ color:'FFFFFF' }, line:{ color:DASH, width:1, dashType:'dash' } });
