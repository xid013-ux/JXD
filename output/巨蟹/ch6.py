b.h('7、行业发展趋势')
b.para(
    '（1）由整机厂商自研自供转向专业供应商联合开发与模块化采购')
b.para(
    '现阶段整机厂商普遍通过垂直整合或与少数伙伴联合开发的方式获得执行器。'
    '执行器领域尚未出现类似汽车发动机供应商的专业角色，行业仍处于前模块化阶段。'
    '整机厂商选择自研，主要是因为可选供应商有限、需要自行把控成本与性能、'
    '保护知识产权并加快迭代，并非长期的战略偏好。整机厂商目前也难以给出供应商'
    '投入大规模研发与工装所需的长期采购量承诺。自研格局因此会延续至出货量'
    '趋于可预测，届时由供应商主导的模块化才在规模上具备经济性。')
b.para(
    '产业价值中心的迁移可分为三个阶段：2025年以前为技术验证阶段，'
    '价值集中在整机厂；2026年至2030年为规模量产阶段，整机厂与关节模组厂商'
    '共同主导；2030年以后进入产业成熟阶段，由关节模组一级供应商主导。'
    '这一转变的成立需要三个前提：下游出货量达到可预测的规模、关节模组的接口与'
    '规格形成一定程度的标准化、供应商具备稳定的批量交付与一致性保障能力。'
    '更可能的形态是自研与外购并行，整机厂商在差异化环节保留自研，在标准化'
    '程度较高的规格上转向外购。对公司而言，未来数年是进入头部整机厂商供应'
    '体系的窗口期。')
b.para(
    '（2）核心零部件国产化率持续提升')
b.para(
    '国产零部件的批量应用直接降低了关节模组的整体成本，并缩短了供应链响应周期。'
    '国产化率的提升'
    '同时改变了竞争的比较对象，该环节的竞争已由进口替代转向国产厂商之间的'
    '技术与成本比较，产品价格随之下行。来福谐波的谐波减速器平均售价由2023年的'
    '795元降至2024年的722元，2025年进一步降至571元。在此'
    '背景下，具备核心零部件自研与量产能力的厂商，在成本控制上的自主空间相对更大。')
b.para(
    '（3）竞争维度由单点性能转向工业化能力')
b.para(
    '在实验室与样机阶段，行业比较的是峰值扭矩、功率密度等极限指标；进入规模化'
    '量产阶段后，量产一致性、使用寿命、环境适应性、长期稳定性和自动化制造'
    '良品率成为主要比较维度。竞争重点由能否完成产品开发转向能否稳定实现规模化'
    '制造，可复制的制造能力构成新的竞争壁垒，不能提供一体化方案的模组厂商'
    '将逐步边缘化。')

b.h('8、行业面临的机遇与风险')
b.para('（1）行业面临的机遇')
b.para(
    '第一，政策支持具有持续性和指向性。减速器与电驱动执行器连续出现在国家层面的'
    '攻关方向和鼓励类目录中，支持对象已由机器人整机细化至具体部组件，本环节企业'
    '在研发立项、资质认定和应用推广方面持续受益。')
b.para(
    '第二，下游由小批量试制转入规模化量产，带来确定性的增量需求。单台整机使用的'
    '关节模组数量以十计，整机出货量的增长会成倍放大至本环节；批量采购同时取代'
    '样机阶段的零星采购，订单的连续性和可预测性随之改善。')
b.para(
    '第三，上游国产配套成熟，为本环节的成本与交付提供支撑。关键原材料和外购件的'
    '国内供应已具备规模，采购半径缩短带来更短的响应周期和更低的库存占用，'
    '本环节企业在成本控制上的自主空间随之扩大。')
b.para('（2）行业面临的风险')
b.para(
    '第一，下游商业化节奏存在不确定性。各机构对人形机器人出货量的统计口径和预测'
    '结果差异较大；地方政府及国资平台是当前的重要采购方，'
    '需求节奏与产业政策和财政安排相关。')
b.para(
    '第二，行业标准与检测评价体系仍在建设过程中。《人形机器人与具身智能标准体系'
    '（2026版）》于2026年3月发布，提出到2028年完成100项以上重点标准，'
    '产品验证与性能比较的统一依据仍需进一步完善。')
b.para(
    '第三，关节技术路线存在分化。据觅途咨询判断，准直驱方案已完成工程化验证，'
    '预计2027年至2028年将占据下肢关节30%以上的份额；肩、肘、腕等上半身精密关节'
    '仍以谐波方案为主。不同部位的技术路线选择存在变化的可能。')
b.para(
    '第四，下游客户集中度较高。人形机器人整机环节目前由少数头部厂商主导，'
    '其量产节奏决定本环节的订单分布，核心零部件供应商普遍存在对单一或少数'
    '客户销售占比较高的情形；若主要客户的量产计划、供应商结构或自制比例发生变化，'
    '将对本环节企业的经营业绩产生较大影响。')

b.h('9、行业周期性特征')
b.para(
    '本行业的下游以人形机器人和工业自动化设备为主。人形机器人处于产业化早期，'
    '需求增长主要由技术进步和商业化进程驱动，尚未形成明显的周期性特征；'
    '协作机器人和工业机器人的需求与制造业固定资产投资周期相关，存在一定的'
    '周期波动。本行业不存在明显的季节性和区域性特征。')

