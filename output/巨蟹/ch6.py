b.h('6、行业发展趋势')
b.para(
    '（1）由整机厂商自研自供转向专业供应商联合开发与模块化采购')
b.para(
    '现阶段整机厂商普遍通过垂直整合或与少数伙伴联合开发的方式获得执行器。'
    '根据麦肯锡的研究，人形机器人执行器领域尚不存在类似汽车发动机供应商的角色，'
    '行业处于前模块化阶段；整机厂商选择自研，主要原因是可选供应商有限、需要控制'
    '成本与性能、保护知识产权并加快迭代，而非长期的战略偏好。该研究同时指出，'
    '整机厂商目前难以提供供应商投入大规模研发与工装所需的长期采购量承诺，'
    '因此自研格局将持续至出货量趋于可预测，届时由供应商主导的模块化才在规模上'
    '具备经济性。')
b.para(
    '这一转变的成立需要三个前提：下游出货量达到可预测的规模、关节模组的接口与'
    '规格形成一定程度的标准化、供应商具备稳定的批量交付与一致性保障能力。'
    '上述前提尚在形成过程中，因此不宜认为整机厂商将放弃自研；更可能的形态是'
    '自研与外购并行，整机厂商在差异化环节保留自研，在标准化程度较高的规格上'
    '转向外购。对公司而言，未来数年是进入头部整机厂商供应体系的窗口期，'
    '能否在特定规格上建立稳定的批量供应记录，将影响其在产业分工形成后的位置。')
b.para(
    '（2）核心零部件国产化率持续提升')
b.para(
    '如前所述，谐波减速机、无框力矩电机等环节已形成规模化的国产供应，'
    '国产零部件的批量应用直接降低了关节模组的整体成本，并缩短了供应链响应周期。'
    '国产化率的提升'
    '同时改变了竞争的比较对象，该环节的竞争已由进口替代转向国产厂商之间的'
    '技术与成本比较，产品价格随之下行。以来福谐波披露的数据为例，其谐波减速器'
    '平均售价由2023年的795元降至2024年的722元，2025年进一步降至571元。在此'
    '背景下，具备核心零部件自研与量产能力的厂商，在成本控制上的自主空间相对更大。')
b.para(
    '（3）竞争维度由单点性能转向工业化能力')
b.para(
    '在实验室与样机阶段，行业比较的是峰值扭矩和传动精度；进入规模化量产阶段后，'
    '量产一致性、交付稳定性、良品率和成本控制成为主要比较维度，可复制的制造能力'
    '构成新的竞争壁垒。')

b.h('7、行业面临的机遇与风险')
b.para('（1）行业面临的机遇')
b.para(
    '第一，产业政策持续支持核心零部件攻关。《人形机器人创新发展指导意见》将'
    '高力矩密度减速器与伺服驱动器融合的高精度电驱动执行器列为重点攻关方向，'
    '《产业结构调整指导目录（2024年本）》将机器人用高精密减速器列入鼓励类，'
    '核心零部件环节获得持续的政策支持。')
b.para(
    '第二，下游进入规模化量产阶段带来增量需求。2026年全球头部整机厂商的产能规划'
    '合计突破10万台、实际交付预计达到4万至6万台，同年我国机器人关节模组出货量'
    '预计达到156万台，下游放量直接转化为本环节的订单增量。')
b.para(
    '第三，国产供应链配套成熟支撑成本下降。人形机器人核心零部件整体国产化率'
    '已提升至75%，国内在精密轴承、功率电子等上游环节具备规模化供应能力，为本环节'
    '企业的成本控制和交付效率提供了支撑。')
b.para('（2）行业面临的风险')
b.para(
    '第一，下游商业化节奏存在不确定性。人形机器人处于产业化早期，各机构对出货量'
    '的统计口径和预测结果差异较大；地方政府及国资平台是当前的重要采购方，'
    '需求节奏与产业政策和财政安排相关。')
b.para(
    '第二，行业标准与检测评价体系仍在建设过程中。《人形机器人与具身智能标准体系'
    '（2026版）》于2026年3月发布，提出到2028年完成100项以上重点标准，'
    '产品验证与性能比较的统一依据仍需进一步完善。')
b.para(
    '第三，关节技术路线存在分化。据觅途咨询判断，准直驱方案已完成工程化验证，'
    '预计2027年至2028年将占据下肢关节30%以上的份额；肩、肘、腕等上半身精密关节'
    '仍以谐波方案为主。不同部位的技术路线选择存在变化的可能。')
b.para(
    '第四，下游客户集中度较高。人形机器人整机环节目前由少数头部厂商主导，'
    '其量产节奏决定本环节的订单分布，核心零部件供应商普遍存在对单一或少数'
    '客户销售占比较高的情形；若主要客户的量产计划、供应商结构或自制比例发生变化，'
    '将对本环节企业的经营业绩产生较大影响。')

b.h('8、行业周期性特征')
b.para(
    '本行业的下游以人形机器人和工业自动化设备为主。人形机器人处于产业化早期，'
    '需求增长主要由技术进步和商业化进程驱动，尚未形成明显的周期性特征；'
    '协作机器人和工业机器人的需求与制造业固定资产投资周期相关，存在一定的'
    '周期波动。本行业不存在明显的季节性和区域性特征。')

