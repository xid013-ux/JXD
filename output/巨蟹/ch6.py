# -------------------- （三）行业发展情况 --------------------
b.h('（三）行业发展情况')

b.h('1、一体化关节模组')
b.para(
    '一体化关节模组是将电机、减速机、驱动器、编码器和力矩传感器集成为标准化动力'
    '单元的机电执行部件，按运动形式分为旋转执行器和线性执行器。旋转执行器按传动'
    '方案分为谐波减速机方案、行星减速机方案和准直驱方案等，其中谐波减速机方案'
    '减速比通常为30至300比1，结构紧凑、精度高，是肩、肘、腕、腰等上半身精密关节'
    '的主流方案。')
b.para(
    '关节模组是人形机器人中价值量最高的硬件环节。根据觅途咨询数据，关节模组占'
    '人形机器人整机物料成本的35%至60%。2025年全球人形机器人关节模组需求量约72万个，'
    '其中旋转关节68.0万个、直线关节4.0万个；按整机归属划分，国产人形机器人整机的'
    '需求量为50.2万个，占全球需求的70%。')
