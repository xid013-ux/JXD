h3('1.3 人形机器人的基本构成——以旋转关节与一体化动力关节模组为例')
para('人形机器人本体由执行系统、感知系统、计算系统、结构件与能源系统共同构成。其中执行系统是价值量最高、技术壁垒最集中的部分，也是无锡巨蟹智能驱动科技有限公司（以下简称"无锡巨蟹"）所处的环节。执行系统按运动形式分为旋转执行器（旋转关节）和线性执行器（直线关节）两类：旋转关节以"电机＋减速器＋编码器＋驱动器＋力矩传感器"为基本结构，广泛用于颈部、肩、肘、腕、腰和髋等部位；线性执行器以"力矩电机＋行星滚柱丝杠"为主，主要用于膝、踝等需要大推力和高刚度的部位。')
para('以旋转关节为例，各组成部分的功能分工如下：无框力矩电机（或空心杯电机）提供原始扭矩和转速；谐波减速器将高转速低扭矩转换为低转速高扭矩输出，同时保证极小的回差和较高的传动精度；编码器分别安装在电机端和输出端（即"双编码器"配置），前者用于电流环和速度环换向控制，后者用于消除减速器柔性变形和回差带来的位置误差，实现输出端的高精度闭环；驱动器完成电流采样、功率放大、力矩控制和总线通信，是关节的"神经末梢"；力矩传感器直接测量关节输出端的真实力矩，使机器人能够感知接触力并实现柔顺控制、碰撞检测和人机安全交互，是关节由"位置控制"走向"力控"的关键部件；制动器和散热结构则用于保障断电安全和连续工作能力。')
para('所谓"一体化动力关节模组"，是指把上述部件在机械、电气和控制三个层面深度集成为一个可直接装配的标准单元，对外只保留机械安装面、动力线和通信总线接口。就无锡巨蟹的产品而言，其集成范围涵盖谐波减速器、驱动器、双编码器、力矩传感器和制动器五类部件。相较于整机厂自行采购分立部件再装配，一体化模组能够显著缩短本体开发周期，减少装配公差累积，降低线束数量和整机重量，并把关节层面的标定、补偿和保护逻辑固化在模组内部。据行业白皮书判断，一体化设计是规模化量产的必选项，无法提供一体化方案的模组厂商在未来两年将快速边缘化。无锡巨蟹的产品体系正是沿着"自研谐波减速器＋自研微型低压驱动器＋自研编码器→系列化一体化关节模组→上肢平台/机械臂"这条路径展开的，其中力矩传感器与编码器同为关节的感知部件，共同决定关节的闭环控制能力。')

