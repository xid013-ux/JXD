para('人形机器人本体由执行系统、感知系统、计算系统、结构件与能源系统共同构成。其中执行系统是价值量最高、技术壁垒最集中的部分，也是无锡巨蟹智能驱动科技有限公司（以下简称"无锡巨蟹"）所处的环节。执行系统按运动形式分为旋转执行器（旋转关节）和线性执行器（直线关节）两类：旋转关节以"电机＋减速器＋编码器＋驱动器"为基本结构，广泛用于颈部、肩、肘、腕、腰和髋等部位；线性执行器以"力矩电机＋行星滚柱丝杠"为主，主要用于膝、踝等需要大推力和高刚度的部位。')
