# -*- coding: utf-8 -*-
from openpyxl import Workbook
from openpyxl.styles import Font, Alignment, PatternFill, Border, Side
from openpyxl.utils import get_column_letter

wb = Workbook(); wb.remove(wb.active)
HDR = PatternFill('solid', fgColor='123F63')
SUB = PatternFill('solid', fgColor='DCE6EE')
HF = Font(name='等线', size=10.5, bold=True, color='FFFFFF')
BF = Font(name='等线', size=10.5)
TF = Font(name='等线', size=11, bold=True, color='123F63')
thin = Side(style='thin', color='B7C4CE')
BD = Border(left=thin, right=thin, top=thin, bottom=thin)

def sheet(name, title, widths):
    ws = wb.create_sheet(name)
    ws.sheet_view.showGridLines = False
    ws['A1'] = title; ws['A1'].font = Font(name='等线', size=13, bold=True, color='123F63')
    ws.row_dimensions[1].height = 24
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = 'A4'
    return ws

def block(ws, row, subtitle, headers, rows, note=None):
    if subtitle:
        ws.cell(row=row, column=1, value=subtitle).font = TF
        row += 1
    for j, h in enumerate(headers, 1):
        c = ws.cell(row=row, column=j, value=h); c.font = HF; c.fill = HDR
        c.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True); c.border = BD
    ws.row_dimensions[row].height = 30
    row += 1
    for r in rows:
        for j, v in enumerate(r, 1):
            c = ws.cell(row=row, column=j, value=v); c.font = BF; c.border = BD
            c.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
        row += 1
    if note:
        c = ws.cell(row=row, column=1, value=note)
        c.font = Font(name='等线', size=9, italic=True, color='666666'); row += 1
    return row + 1

