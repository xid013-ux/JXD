para('第二，口径标注。人形机器人行业尚无统一统计口径，本报告在引用每一项关键数据时均标注其来源机构与统计口径，对同一指标的不同来源数值不作合并或平均，而是并列呈现并说明差异原因。例如，2025年出货量存在"中国2万台（GGII口径）"与"全球1.7万台、中国1.44万台（IDC等口径）"两组数据，本报告分别标注并说明差异主要来自统计边界和是否包含轮式机型。')
para('第三，估值参照的处理。未上市企业的估值均采用公开报道的融资后估值，不进行推算；对已发行企业采用发行价对应的隐含估值。本报告明确说明这些数值不代表实际交易定价，仅用于形成数量级参考。')
para('第四，差异化和不确定性的显性化。对于行业内存在分歧的判断（如第二梯队企业的出货量区间、特斯拉产能规划的可信度），本报告不作单一结论，而是并列呈现不同来源并提示不确定性。')

