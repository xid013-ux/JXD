def mk(name, title, headers, rows, widths, after_notes=None):
    ws = wb.create_sheet(name)
    ws['A1'] = title
    ws['A1'].font = Font(name='微软雅黑', size=12, bold=True, color='123F63')
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(headers))
    ws['A1'].alignment = Alignment(horizontal='left', vertical='center')
    ws.row_dimensions[1].height = 22
    for i, h in enumerate(headers, 1):
        c = ws.cell(row=2, column=i, value=h)
        c.fill = HDR; c.font = HF; c.alignment = C; c.border = BD
    for r, row in enumerate(rows, 3):
        for i, v in enumerate(row, 1):
            c = ws.cell(row=r, column=i, value=v)
            c.font = BF; c.alignment = C; c.border = BD
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = 'A3'
    if after_notes:
        r0 = ws.max_row + 2
        for i, t in enumerate(after_notes):
            c = ws.cell(row=r0 + i, column=1, value=t)
            c.font = Font(name='微软雅黑', size=10,
                          bold=t.startswith('【'), color='123F63' if t.startswith('【') else '000000')
            c.alignment = L
            ws.merge_cells(start_row=r0 + i, start_column=1,
                           end_row=r0 + i, end_column=len(headers))
    return ws

