h2('半导体存储产业概述')

h3('1.1 行业简介')
para('半导体存储器用于数据的存放与读取，是集成电路的主要品类之一。'
     '按数据在断电后是否保留，分为易失性存储器与非易失性存储器两类。'
     '易失性存储器以动态随机存取存储器（DRAM）为代表，用于设备运行时的数据暂存；'
     '非易失性存储器以NAND Flash与NOR Flash为代表，用于数据的长期保存。'
     '这三类产品构成了存储行业的主体，其余如静态随机存取存储器、电可擦可编程只读存储器'
     '以及磁性、阻变、相变等新型存储介质，市场规模相对较小。')

para('存储行业的产品标准化程度高、单一料号出货批量大，产能建设的资本开支密集，'
     '价格随供需变化的波动幅度显著大于多数半导体品类。'
     '本报告的行业边界限定为DRAM、NAND Flash、NOR Flash三类存储芯片，'
     '及其晶圆制造、封装测试、主控芯片、存储模组等环节，不含企业级存储系统与服务器整机。')

h3('1.2 主要产品形态与技术路线')
para('DRAM的技术演进以制程微缩与接口标准升级为主线。'
     '接口标准由DDR3、DDR4向DDR5演进，移动端对应LPDDR3、LPDDR4、LPDDR5系列。'
     '面向人工智能算力需求的高带宽内存（HBM）通过晶粒垂直堆叠与硅通孔互连提升带宽。'
     '据深科技2025年年度报告，DRAM领域头部企业将产能向高带宽内存、DDR5等'
     '高附加值产品倾斜，DDR5在服务器端的渗透率提升并逐步替代DDR4。')

para('NAND Flash的技术演进以三维堆叠层数的提升为主线，'
     '并通过多值存储单元提高单位面积容量。'
     '长江存储自主研发的Xtacking架构已实现232层及以上三维NAND量产。'
     '嵌入式存储方面，eMMC、eMCP、UFS等封装形式面向移动终端与嵌入式设备。')

para('NOR Flash容量较小但读取速度快、可靠性高，主要用于代码存储，'
     '应用于车载电子、工业控制与物联网设备。')

h3('1.3 行业的基本指标')
para('衡量存储行业通常使用四组指标，各自的统计对象不同，不可互相替代。'
     '一是市场规模，以销售额计量，反映价格与出货量的综合结果；'
     '二是位元出货量，以存储容量计量，反映实际供给的数量；'
     '三是晶圆产能，以每月投片的晶圆片数计量，反映产能建设的规模；'
     '四是价格指标，包括现货价、合约价及综合价格指数。')

para('由于单位容量价格随技术节点推进持续下行，位元出货量的增长与销售额的增长'
     '在多数年份并不同步，在价格下行周期中甚至方向相反。'
     '同一厂商按晶圆产能计算的份额与按销售额计算的份额也可能存在显著差异，'
     '差异来源为产品结构与单位晶圆的价值量不同。本报告在引用份额数据时均标注统计对象。')

